function renderQuestionBank(questionBank) {
  return questionBank
    .map((item, index) => `${index + 1}. [${item.category}] ${item.question}\n   - 个性化回答依据：${item.answerGuide}`)
    .join('\n')
}

function renderKnowledgeBase(knowledge) {
  const skills = Object.entries(knowledge.skills)
    .map(([group, items]) => `- ${group}：${items.join('、')}`)
    .join('\n')

  const projects = knowledge.projects
    .map((project) => [
      `### ${project.name}`,
      `- 身份与场景：${project.role}；${project.audience}`,
      `- 技术与方法：${project.methods.join('、')}`,
      ...project.evidence.map((item) => `- 事实证据：${item}`),
    ].join('\n'))
    .join('\n\n')

  return `
## 身份与求职方向
- 姓名：${knowledge.identity.name}
- 目标岗位：${knowledge.identity.targetRole}
- 所在地：${knowledge.identity.location}
- 定位：${knowledge.identity.positioning}
- 联系方式：电话 ${knowledge.identity.phone}；邮箱 ${knowledge.identity.email}；微信 ${knowledge.identity.wechat}
- 作品集：${knowledge.identity.portfolio}

## 个人概述
${knowledge.summary.map((item) => `- ${item}`).join('\n')}

## 专业技能
${skills}

## 项目证据
${projects}

## 应用与服务经历
${knowledge.serviceExperience.map((item) => `- ${item}`).join('\n')}

## 教育、荣誉与证书
- 教育：${knowledge.education.school}，${knowledge.education.major} ${knowledge.education.degree}，${knowledge.education.period}
- 荣誉：${knowledge.awards.join('、')}
- 证书：${knowledge.certificates.join('、')}
  `.trim()
}

